"""Generate shopkit/api_client.py from spec/api.yaml.

Spec format: endpoints.<name>: method, path, params (positional), optional `options` mapping of
keyword argument -> default value (Python literal), passed through to the transport.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def parse(text: str) -> dict:
    spec, endpoints, cur, section = {}, {}, None, None
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].rstrip()
        if not line.strip():
            continue
        indent = len(line) - len(line.lstrip())
        key, _, val = line.strip().partition(":")
        val = val.strip()
        if indent == 0:
            section = key
            if val:
                spec[key] = val
        elif indent == 2 and section == "endpoints":
            cur = endpoints.setdefault(key, {"params": [], "options": {}})
        elif indent == 4 and cur is not None:
            if key == "params":
                cur["params"] = [p.strip() for p in val.strip("[]").split(",") if p.strip()]
            elif key == "options":
                cur["options"] = {}
            else:
                cur[key] = val
        elif indent == 6 and cur is not None:
            cur["options"][key] = val
    spec["endpoints"] = endpoints
    return spec


def render(spec: dict) -> str:
    out = ["# GENERATED by tools/gen_client.py from spec/api.yaml. Do not edit by hand.", "",
           f"BASE_URL = {spec['base_url']!r}", "", ""]
    for name, ep in spec["endpoints"].items():
        args = list(ep["params"]) + [f"{k}={v}" for k, v in ep["options"].items()]
        out.append(f"def {name}(transport{''.join(', ' + a for a in args)}):")
        fmt = ", ".join(f"{p}={p}" for p in ep["params"])
        kw = "".join(f", {k}={k}" for k in ep["options"])
        out.append(f"    return transport({ep['method']!r}, BASE_URL + {ep['path']!r}.format({fmt}){kw})")
        out.append("")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


if __name__ == "__main__":
    (ROOT / "shopkit" / "api_client.py").write_text(render(parse((ROOT / "spec" / "api.yaml").read_text())))
